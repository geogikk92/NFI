// Вграждане на структурирани данни.
//
// Отделен компонент, за да е на едно място решението КАК се сериализира:
// `<` в JSON стойност затваря скрипта и отваря дупка за инжекция, ако
// съдържанието идва от базата (а то идва — заглавия на курсове).

export function JsonLd({ data }: { data: unknown }) {
  // Екранирането на „<" е задължително: заглавие на курс от админа,
  // съдържащо „<script", иначе излиза от JSON блока.
  const json = JSON.stringify(data).replace(/</g, "\\u003c");

  return (
    <script
      type="application/ld+json"
      // Съдържанието е наше и е екранирано — единственият начин да се
      // вгради JSON-LD в React без да се разбие на текстови възли.
      dangerouslySetInnerHTML={{ __html: json }}
    />
  );
}
