// АДМИН · задача 17a — пазачът на /admin.
//
// ЕДИНСТВЕНОТО място в проекта, където се решава кой влиза в админа.
// Ако някога се появи втора проверка, тя ще се разминае с тази — затова
// всяка страница под app/admin/ вика requireAdmin() и нищо друго.
//
// „server-only" не е украса: файлът внася Prisma и попадне ли в клиентски
// компонент, pg влиза в браузърния бъндъл и маршрутът дава 500. Така
// грешката излиза при компилация, а не в продукция.
import "server-only";

import { cache } from "react";
import { notFound } from "next/navigation";
import { db } from "@/lib/db";

export interface AdminUser {
  id: string;
  email: string;
  name: string | null;
}

/**
 * Отказът е 404, не 403.
 *
 * Причината: 403 потвърждава, че на този адрес ИМА админ, и приканва към
 * опити. Истинската причина отива в лога на сървъра — Василена не бива да
 * гадае защо панелът е изчезнал, но и чужд човек не бива да я прочете.
 */
function deny(reason: string): never {
  console.error(`[admin] Отказан достъп: ${reason}`);
  notFound();
}

/**
 * Проверка на роля за целия админ панел.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  ВРЕМЕННО СЪСТОЯНИЕ. Auth.js сесиите още не са закачени (по тях работи
 *  друг агент, регистрацията е задача 15). Затова тялото по-долу разчита
 *  на ADMIN_EMAIL от средата и СВЕРЯВА роля срещу базата.
 *
 *  Щом сесиите дойдат, тук се сменят само първите редове:
 *
 *      const session = await auth();
 *      const email = session?.user?.email;
 *      if (!email) redirect("/anmelden?next=/admin");
 *
 *  и ADMIN_EMAIL отпада. Проверката на ролята срещу базата ОСТАВА —
 *  роля от токен/сесия е снимка и остарява при отнемане на права.
 *
 *  Какво НЕ се прави тук, колкото и да е удобно: фалшив вход и „ако няма
 *  сесия, пускай". Недостъпен админ е неудобство; отворен админ е инцидент
 *  с лични данни (заявки за обаждане с име, имейл и телефон).
 * ─────────────────────────────────────────────────────────────────────────
 *
 * Обвито е в React `cache()`: layout-ът и страницата под него викат
 * функцията независимо, а Next мемоизира само `fetch()`, не и Prisma —
 * иначе всяко зареждане на админ страница прави две еднакви заявки.
 */
export const requireAdmin = cache(async (): Promise<AdminUser> => {
  const configured = process.env.ADMIN_EMAIL?.trim();

  // Липсващата променлива заключва панела НАРОЧНО. Обратното — „няма
  // ADMIN_EMAIL, значи всеки е админ" — е точно начинът, по който админи
  // остават отворени в продукция.
  if (!configured) {
    deny(
      "ADMIN_EMAIL липсва в средата. Добави го в .env.local с имейла на " +
        "потребителя с роля ADMIN.",
    );
  }

  const user = await db.user.findFirst({
    where: {
      // Регистърът е без значение: Postgres пази имейла както е въведен, а
      // в .env.local лесно се озовава с главна буква. Сравнение „както е"
      // би заключило истинския админ без никакъв видим повод.
      email: { equals: configured, mode: "insensitive" },
      // Ролята е ЕДИНСТВЕНИЯТ носител на правото. Имейлът в средата само
      // казва „кой", не „с какви права" — иначе панелът се отваря с една
      // променлива в средата.
      role: "ADMIN",
      // Меко изтритият профил не влиза, макар редът му да е в базата.
      deletedAt: null,
    },
    select: { id: true, email: true, name: true },
  });

  if (!user) {
    deny(
      `Няма активен потребител с роля ADMIN и имейл ${configured}. ` +
        "Провери ADMIN_EMAIL и колоната User.role.",
    );
  }

  return user;
});
