// АДМИН · задача 17a — пазачът на /admin.
//
// ЕДИНСТВЕНОТО място в проекта, където се решава кой влиза в админа.
// Ако някога се появи втора проверка, тя ще се разминае с тази — затова
// всяка страница под app/admin/ вика requireAdmin() и нищо друго.
//
// „server-only" не е украса: файлът внася Prisma и попадне ли в клиентски
// компонент, pg влиза в браузърния бъндъл и маршрутът дава 500. Така
// грешката излиза при компилация, а не в продукция.
import "server-only";

import { cache } from "react";
import { notFound } from "next/navigation";
import { db } from "@/lib/db";
import { currentUser } from "@/lib/auth/session-db";

export interface AdminUser {
  id: string;
  email: string;
  name: string | null;
}

/**
 * Отказът е 404, не 403.
 *
 * Причината: 403 потвърждава, че на този адрес ИМА админ, и приканва към
 * опити. Истинската причина отива в лога на сървъра — Василена не бива да
 * гадае защо панелът е изчезнал, но и чужд човек не бива да я прочете.
 */
function deny(reason: string): never {
  console.error(`[admin] Отказан достъп: ${reason}`);
  notFound();
}

/**
 * Проверка на самоличност И роля за целия админ панел.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  ИСТОРИЯ, за да не се върне: до 30.07.2026 тук се четеше ADMIN_EMAIL от
 *  средата и се сверяваше срещу базата — но НЕ се проверяваше КОЙ Е
 *  ПОСЕТИТЕЛЯТ. Тоест зададеше ли се променливата в продукция, панелът се
 *  отваряше за целия интернет, а /admin/anketi показва имена, имейли и
 *  телефони на заявилите обаждане. Проверката отговаряше на въпроса
 *  „съществува ли админ", а трябва да отговаря на „ти ли си той".
 *
 *  ADMIN_EMAIL вече НЕ дава достъп на никого. Остава само като
 *  предпазител: посочи ли различен имейл от влезлия, достъпът пада.
 * ─────────────────────────────────────────────────────────────────────────
 *
 * Двете проверки са нарочно отделни:
 *   1. сесията казва КОЙ е (bcrypt/scrypt парола + непрозрачен токен);
 *   2. базата казва С КАКВИ ПРАВА е — в момента, не когато е влязъл.
 *
 * Роля, носена от сесията, е снимка: отнемеш ли правата на човек, той
 * остава админ до изтичане на токена. Затова ролята се чете при всяка
 * заявка, а не се копира в сесията.
 *
 * Обвито е в React `cache()`: layout-ът и страницата под него викат
 * функцията независимо, а Next мемоизира само `fetch()`, не и Prisma —
 * иначе всяко зареждане на админ страница прави две еднакви заявки.
 */
export const requireAdmin = cache(async (): Promise<AdminUser> => {
  // 1. КОЙ. Няма сесия → няма достъп. Точка.
  const visitor = await currentUser();
  if (!visitor) {
    deny("Няма сесия. Непознат посетител на /admin.");
  }

  // 2. С КАКВИ ПРАВА — чете се сега, от базата, не от сесията.
  const user = await db.user.findFirst({
    where: {
      id: visitor.id,
      // Ролята е ЕДИНСТВЕНИЯТ носител на правото.
      role: "ADMIN",
      // Меко изтритият профил не влиза, макар редът му да е в базата.
      deletedAt: null,
    },
    select: { id: true, email: true, name: true },
  });

  if (!user) {
    deny(`Потребител ${visitor.email} няма роля ADMIN.`);
  }

  // 3. Предпазител, не право за достъп.
  //
  // Ако ADMIN_EMAIL е зададен, той стеснява кръга до един конкретен човек
  // дори роля ADMIN да получи някой друг — например по грешка в сийд или
  // в ръчна заявка. Липсва ли, ролята е достатъчна.
  const restrictTo = process.env.ADMIN_EMAIL?.trim();
  if (restrictTo && restrictTo.toLowerCase() !== user.email.toLowerCase()) {
    deny(
      `ADMIN_EMAIL сочи ${restrictTo}, а влезлият е ${user.email}. ` +
        "Или махни променливата, или я изравни с имейла на админа.",
    );
  }

  return user;
});
