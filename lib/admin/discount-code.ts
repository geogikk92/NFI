export interface DiscountState {
  active: boolean;
  startsAt: Date | null;
  endsAt: Date | null;
  maxRedemptions: number | null;
  redemptions: number;
}

export type DiscountStatus =
  | "active"
  | "off"
  | "pending"
  | "expired"
  | "used-up";

export const DISCOUNT_STATUS_LABELS: Record<DiscountStatus, string> = {
  active: "Работи",
  off: "Изключена",
  pending: "Още не важи",
  expired: "Изтекла",
  "used-up": "Изчерпана",
};

/**
 * Защо кодът НЕ работи в момента — или че работи.
 *
 * Съществува, защото „включена" не значи „работи": код с изтекъл срок или
 * изчерпан лимит стои с отметка „активна" и изглежда изправен, а клиентът
 * получава отказ. Списъкът показва истинското състояние, не отметката.
 *
 * Редът на проверките повтаря ТОЧНО реда в lib/commerce/pricing.ts —
 * разминат ли се двата, панелът ще твърди едно, а касата ще прави друго.
 */
export function discountStatus(
  discount: DiscountState,
  now: Date = new Date(),
): DiscountStatus {
  if (!discount.active) return "off";
  if (discount.startsAt && now < discount.startsAt) return "pending";
  if (discount.endsAt && now > discount.endsAt) return "expired";
  if (
    discount.maxRedemptions !== null &&
    discount.redemptions >= discount.maxRedemptions
  ) {
    return "used-up";
  }
  return "active";
}
