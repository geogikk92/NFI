// АДМИН · промоционалният код — правила, общи за формата и за сървъра.
//
// ЧИСТ модул: без база и без "server-only". Формата го вика в браузъра, за
// да покаже кода такъв, какъвто ще бъде записан, а server action-ът го вика
// пак — една функция, не две, иначе показаното и записаното се разминават.

/**
 * Кодът се записва С ГЛАВНИ БУКВИ и без интервали.
 *
 * ─────────────────────────────────────────────────────────────────────────
 *  НЕ Е РАЗКРАСЯВАНЕ. Търсенето при плащане прави
 *
 *      db.discount.findUnique({ where: { code: input.trim().toUpperCase() } })
 *
 *  (lib/commerce/catalog.ts). Код, записан като „leto2026", НЕ МОЖЕ да
 *  бъде намерен никога — нито грешка в лога, нито следа, просто
 *  „невалиден код" пред всеки клиент, който го е получил в реклама.
 * ─────────────────────────────────────────────────────────────────────────
 *
 * Интервалите падат, защото клиентът ги губи при копиране и после кодът
 * „не работи" по причина, невидима и за двете страни.
 */
export function normalizeCode(input: string): string {
  return input.replace(/\s+/g, "").toUpperCase();
}

export const MIN_CODE_LENGTH = 3;
export const MAX_CODE_LENGTH = 32;

/**
 * Кирилските букви, които изглеждат като латински.
 *
 * Ето защо това има значение: „ЛЯТО2026" се пише лесно на българска
 * клавиатура и изглежда като нормален код. Клиентът в Германия го вижда в
 * писмо, набира го на своята клавиатура и получава „невалиден код" — а
 * набраното изглежда БУКВА ПО БУКВА еднакво с показаното.
 *
 * Най-лошият случай е смесеният: „СТАРТ" с кирилско „С" и латинско „Т" е
 * невъзможен за въвеждане от когото и да е, включително от този, който го
 * е създал, ако смени клавиатурата.
 */
// `\p{Script=Cyrillic}`, а не диапазон с буквални знаци: диапазонът се
// пише с невидими за окото символи в кода и всяко нормализиране на файла
// го разваля мълчаливо. Свойството покрива и разширенията на азбуката.
const CYRILLIC = /\p{Script=Cyrillic}/u;

/**
 * Валиден ли е кодът. Връща обяснение или `null`.
 *
 * Проверява се ВЕЧЕ НОРМАЛИЗИРАН код — тоест малките букви и интервалите
 * не са грешка, а се поправят мълчаливо преди това.
 */
export function codeProblem(code: string): string | null {
  if (code.length === 0) {
    return "Кодът е задължителен.";
  }

  if (CYRILLIC.test(code)) {
    return (
      "Кодът съдържа кирилица. Клиентите в Германия не могат да я наберат, " +
      "а на екрана „С“ и „C“ изглеждат еднакво — кодът просто няма да " +
      "работи и никой няма да разбере защо. Ползвай латински букви и цифри."
    );
  }

  if (code.length < MIN_CODE_LENGTH) {
    return `Кодът е под ${MIN_CODE_LENGTH} знака — прекалено лесен за налучкване.`;
  }

  if (code.length > MAX_CODE_LENGTH) {
    return `Кодът е над ${MAX_CODE_LENGTH} знака и не се преписва от човек.`;
  }

  // Същата форма като при адресите: групи от букви и цифри, разделени с
  // едно тире. Отхвърля водещо, крайно и двойно тире — трите вида
  // невалидно ръчно писане.
  if (!/^[A-Z0-9]+(-[A-Z0-9]+)*$/.test(code)) {
    return (
      "Кодът може да съдържа само латински главни букви, цифри и тире " +
      "между тях."
    );
  }

  return null;
}

