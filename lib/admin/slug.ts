// АДМИН · основа — адресната част на курс, продукт и материал.
//
// ЧИСТ модул: без база и без "server-only". Формата го вика в БРАУЗЪРА, за
// да предложи адрес още докато се пише заглавието, а server action-ът го
// вика пак на сървъра. Двете извиквания трябва да дадат едно и също нещо,
// затова функцията е една, а не две.
//
// Защо изобщо има транслитерация: заглавието е кирилица („Немски A1 ·
// вечерен курс"), а адресът трябва да е латиница. Кирилица в адрес работи,
// но при копиране става на %D0%9D%D0%B5... — нечетимо в имейл и в реклама.
//
// Съществуващите адреси идват от НЕМСКОТО заглавие, не от българското:
// „deutsch-a1-abendkurs", „pruefungsvorbereitung-b2". Затова
// suggestSlug() гледа първо немското поле.

/**
 * Немските гласни с умлаут НЕ отпадат до гола гласна.
 *
 * „Prüfung" → „prufung" е грешно за немски: официалното заместване е „ue",
 * оттам и същестуващият адрес „pruefungsvorbereitung-b2". Правилото важи и
 * за ß → ss („Straße" → „strasse").
 *
 * Тази таблица се прилага ПРЕДИ махането на диакритиката отдолу — иначе
 * Unicode нормализацията вече е свалила двете точки и „ü" е станало „u".
 */
const GERMAN: ReadonlyArray<readonly [RegExp, string]> = [
  [/ä/g, "ae"],
  [/ö/g, "oe"],
  [/ü/g, "ue"],
  [/ß/g, "ss"],
];

/**
 * Официалната българска транслитерация (Закон за транслитерацията, 2009).
 *
 * Не е измислена таблица: същата се ползва в личните документи, така че
 * „Николова" дава „nikolova" и в паспорта, и в адреса.
 */
const BULGARIAN: Readonly<Record<string, string>> = {
  а: "a",
  б: "b",
  в: "v",
  г: "g",
  д: "d",
  е: "e",
  ж: "zh",
  з: "z",
  и: "i",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "h",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "sht",
  ъ: "a",
  ь: "y",
  ю: "yu",
  я: "ya",
};

/** По-дълъг адрес не се побира в поле и не се чете. Prisma не ограничава. */
export const MAX_SLUG_LENGTH = 80;

/**
 * Заглавие → адресна част.
 *
 * Редът на стъпките е съществен и всяка разместена стъпка чупи нещо:
 *   1. немските умлаути — преди нормализацията, иначе стават голи гласни;
 *   2. кирилицата — по буква, защото „щ" дава ТРИ латински знака;
 *   3. останалата диакритика (é, ñ, å) — сваля се до основната буква;
 *   4. всичко, което не е буква или цифра → тире.
 *
 * Резултатът е само [a-z0-9-]: точката „·" от заглавията, интервалите и
 * кавичките изчезват.
 */
export function slugify(input: string): string {
  let text = input.toLowerCase().trim();

  for (const [pattern, replacement] of GERMAN) {
    text = text.replace(pattern, replacement);
  }

  // Буква по буква, защото заместванията са с различна дължина.
  text = Array.from(text)
    .map((char) => BULGARIAN[char] ?? char)
    .join("");

  // NFD разделя „é" на „e" + знак за ударение, после знакът се маха.
  //
  // `\p{M}` (всички комбиниращи знаци), не диапазонът U+0300–U+036F: вторият
  // покрива само латинския блок и пропуска останалите, а и се пише с
  // буквални невидими знаци в кода — ред, който никой не може да прочете и
  // който всяко нормализиране на файла мълчаливо разваля.
  text = text.normalize("NFD").replace(/\p{M}/gu, "");

  text = text
    .replace(/[^a-z0-9]+/g, "-")
    // Водещото и крайното тире идват от препинателен знак в края.
    .replace(/^-+|-+$/g, "");

  if (text.length <= MAX_SLUG_LENGTH) return text;

  // Отрязва се по ГРАНИЦА НА ДУМА, не по буква: „deutsch-a1-abendku" е
  // по-лошо от „deutsch-a1", а разликата е един lastIndexOf.
  const cut = text.slice(0, MAX_SLUG_LENGTH);
  const lastDash = cut.lastIndexOf("-");
  return (lastDash > 0 ? cut.slice(0, lastDash) : cut).replace(/-+$/g, "");
}

/**
 * Кое заглавие ражда адреса.
 *
 * Немското е с предимство, защото немският е основният език на сайта и
 * защото досегашните адреси са такива. Липсва ли, българското върши
 * работа — админът вижда предложението и може да го поправи.
 */
export function suggestSlug(titles: {
  de?: string | null;
  bg?: string | null;
}): string {
  const source = titles.de?.trim() || titles.bg?.trim() || "";
  return slugify(source);
}

/**
 * Валиден ли е адрес, въведен на ръка.
 *
 * Админът може да пренапише предложението и това е нарочно — адресът е
 * URL и се сменя рядко, но понякога трябва. Проверката е СТРОГА, защото
 * невалиден адрес се вижда чак когато страницата даде 404.
 */
export function slugProblem(value: string): string | null {
  if (value.length === 0) return "Адресът не може да е празен.";

  if (value.length > MAX_SLUG_LENGTH) {
    return `Адресът е по-дълъг от ${MAX_SLUG_LENGTH} знака.`;
  }

  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(value)) {
    return (
      "Адресът може да съдържа само малки латински букви, цифри и тире " +
      "между тях — без интервали, кирилица и препинателни знаци."
    );
  }

  // Само цифри би се сблъскало с бъдещ адрес по номер и се чете като
  // грешка дори от човек.
  if (/^\d+$/.test(value)) {
    return "Адресът не може да е само от цифри.";
  }

  return null;
}
