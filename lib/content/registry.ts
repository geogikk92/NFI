/**
 * Видовете поле. Четири, и нито едно повече.
 *
 * Всеки нов вид е ново поле в редактора, нова валидация и нов начин да се
 * счупи нещо. Ако някога потрябва пети, той трябва да си заслужи мястото.
 */
export type BlockKind =
  /** Многоредов текст. Абзаците са празен ред — без HTML, без Markdown. */
  | "prose"
  /** Един ред: подзаглавие, надпис, кратък факт. */
  | "line"
  /** Дата „01.09.2026" — само ASCII цифри и точки. */
  | "date"
  /** Число или оценка: „22 000+", „4.9". Само ASCII цифри. */
  | "number";

/** Границата по знаци е РАЗЛИЧНА за трите езика. */
export interface BlockLimits {
  bg: number;
  de: number;
  en: number;
}

export interface BlockSpec {
  /** Ключът. ASCII, точки за разделител — става валиден DOM id. */
  key: string;
  /** Коя страница: групира списъка в админа. */
  page: PageId;
  /** Български етикет за Василена. НЕ ключът — „Кои сме ние". */
  label: string;
  /** Едно изречение: къде се вижда това и какво пише вътре. */
  help: string;
  kind: BlockKind;
  max: BlockLimits;
  /**
   * Стойността в КОДА, ако има такава.
   *
   * Има я само за блоковете, които днес показват нещо (датата на старта,
   * броят в общността). За тях базата пази ПРЕЗАПИС: няма ли ред, се
   * показва това. Празна база = днешният сайт дума по дума, а промяна в
   * кода остава жива, вместо да бъде мълчаливо засенчена от сийд.
   *
   * Липсва при блоковете, които клиентката трябва да напише от нулата —
   * там няма какво да падне отдолу и празното е честното състояние.
   */
  codeValue?: (locale: Locale) => string;
}

