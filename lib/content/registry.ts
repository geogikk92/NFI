export const BLOCK_KEYS: readonly string[] = BLOCKS.map((block) => block.key);

const BY_KEY = new Map(BLOCKS.map((block) => [block.key, block]));

/** Спецификацията по ключ, или undefined за непознат ключ. */
export function blockSpec(key: string): BlockSpec | undefined {
  return BY_KEY.get(key);
}

/** Блоковете на една страница, в реда на регистъра. */
export function blocksForPage(page: PageId): BlockSpec[] {
  return BLOCKS.filter((block) => block.page === page);
}

/**
 * Има ли този блок текст в кода, който да се покаже при липсващ презапис.
 *
 * Разликата решава какво става при празно: блок СЪС стойност в кода просто
 * показва нея; блок БЕЗ стойност няма какво да покаже и остава видимо
 * незавършен (виж AwaitingLegalText в публичния компонент).
 */
export function hasCodeFallback(spec: BlockSpec): boolean {
  return typeof spec.codeValue === "function";
}

/** Стойността от кода за този език, или null. */
export function codeValueFor(spec: BlockSpec, locale: Locale): string | null {
  return spec.codeValue ? spec.codeValue(locale) : null;
}

// ─────────────────────────────────────────────────────────────────────────
//  Валидация на стойност
// ─────────────────────────────────────────────────────────────────────────

/**
 * Кирилско „А" в латинско поле е РЕАЛНИЯТ режим на отказ при българска
 * клавиатура: А, В, С, Е, О, Р, Х са визуално неразличими от латинските.
 * Стойност, която влиза в адрес или се сверява с код, трябва да е ASCII.
 */
const ASCII_DATE = /^\d{2}\.\d{2}\.\d{4}$/;
const ASCII_NUMBER = /^[\d\s.,+±–-]+$/;

export type BlockProblem =
  | { code: "too-long"; limit: number; actual: number }
  | { code: "bad-date" }
  | { code: "bad-number" }
  | { code: "empty" };

/**
 * Проверява стойност срещу спецификацията. Връща null, когато е наред.
 *
 * ЕДНА проверка за всички пътища: админ формата, сийдът и CI скриптът я
 * викат. Иначе редакторът отказва текст, който сийдът вече е вкарал.
 */
export function checkBlockValue(
  spec: BlockSpec,
  locale: Locale,
  raw: string,
): BlockProblem | null {
  const value = raw.trim();

  // Празното е ЛЕГИТИМНО: значи „нямам какво да кажа на този език" и
  // блокът пада към кода или остава незавършен. Изтриването на текст е
  // право на редактора, не грешка.
  if (value.length === 0) return null;

  const limit = spec.max[locale];
  if (value.length > limit) {
    return { code: "too-long", limit, actual: value.length };
  }

  if (spec.kind === "date" && !ASCII_DATE.test(value)) {
    return { code: "bad-date" };
  }

  if (spec.kind === "number" && !ASCII_NUMBER.test(value)) {
    return { code: "bad-number" };
  }

  return null;
}

/** Съобщението на български — админът е само на български. */
export function blockProblemMessage(
  spec: BlockSpec,
  problem: BlockProblem,
): string {
  switch (problem.code) {
    case "too-long":
      return `Твърде дълго: най-много ${problem.limit} знака (сега са ${problem.actual}). По-дългият текст излиза извън мястото си в дизайна.`;
    case "bad-date":
      return "Датата се пише като 01.09.2026 — с точки и с латински цифри.";
    case "bad-number":
      return "Тук се пишат само цифри и знаци като + или интервал. Кирилските букви „А“ и „О“ приличат на латинските, но чупят връзките.";
    case "empty":
      return `Полето „${spec.label}“ е задължително.`;
  }
}

/** Абзаците са празен ред. Един договор за целия проект. */
export function toParagraphs(value: string): string[] {
  return value
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);
}
