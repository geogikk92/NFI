import "server-only";

// ТЕРИТОРИЯ НА БОБИ · задача 18c — preview режимът.
//
// Василена натиска „Виж как изглежда“ в админа и вижда ЧЕРНОВАТА върху
// истинската страница, вместо да гадае по полето за въвеждане.
//
// ─────────────────────────────────────────────────────────────────────────
//  ЗАЩО draftMode, А НЕ ПОДПИСАН ТОКЕН В АДРЕСА
// ─────────────────────────────────────────────────────────────────────────
// Токен в адреса се препраща: тя копира линка в имейл до колежка, той
// влиза в история на браузъра, в Referer, в лога на CDN — и черновата
// изтича завинаги. `draftMode` слага HttpOnly бисквитка на СЪЩИЯ браузър,
// която не пътува с копиран адрес.
//
// Включва се от server action с requireAdmin() на първия ред (виж
// app/admin/tekstove/actions.ts). Тоест правото се проверява в момента на
// включване, а не се носи от линка.

import { draftMode } from "next/headers";

/**
 * В preview режим ли сме.
 *
 * НЕ хвърля при липсваща бисквитка и НЕ изисква конфигурация — обикновен
 * посетител просто получава false и вижда публикуваното.
 */
export async function isDraftPreview(): Promise<boolean> {
  try {
    return (await draftMode()).isEnabled;
  } catch {
    // Извън заявка (например при генериране на sitemap) draftMode()
    // хвърля. Там няма чернови — публикуваното е верният отговор.
    return false;
  }
}
