// ТЕРИТОРИЯ НА БОБИ · задача 17m-b — адресът на публично изображение.
//
// ЕДИНСТВЕНОТО място, което строи URL на медия. Един вход = едно място
// за промяна, когато дойде R2 custom domain или CDN.
//
// Адресът е ОТНОСИТЕЛЕН и стабилен (/media/<ключ>), не подписан:
//   • next/image кешира по целия href — подписан URL с менящи се
//     sig/exp прави нов кешов ключ при всяко зареждане, тоест пълен
//     miss и нова платена трансформация; изтекъл подпис дава счупена
//     картинка (оптимизаторът хвърля при не-2xx).
//   • относителният същия-произход път минава през /_next/image БЕЗ
//     remotePatterns — next.config.ts (общ файл) не се пипа заради
//     картинки и оптимизаторът не става отворен прокси към bucket-а.
//
// Кешът е безопасен, защото ключовете са immutable по конструкция:
// newObjectKey() слепва случаен суфикс — един ключ = едно съдържание
// завинаги. Ново съдържание = нов ключ = нов адрес.
//
// Media.variants НАРОЧНО остава NULL и не се чете тук: оразмеряването е
// на next/image (16-те ширини от deviceSizes/imageSizes + WebP/AVIF по
// Accept). Решението е записано в docs/ПЛАН.md, задача 17m — полето
// остава свободно за бъдеща нужда (LQIP, версия за имейл), без миграция.

/**
 * Ключ от scope "media" → публичният му адрес.
 *
 * Ключът ВЕЧЕ започва с "media/" (scope-ът е първият сегмент на всеки
 * ключ) — адресът е просто "/" + ключа, така че сегментът /media в URL-а
 * Е scope-ът, без дублиране: media/2026/x.png → /media/2026/x.png.
 */
export function mediaUrl(key: string): string {
  if (!key.startsWith("media/")) {
    throw new Error(
      `mediaUrl() е само за scope "media", а ключът е „${key}". Платените ` +
        "файлове се дават през signedUrl().",
    );
  }

  // Сегментите се кодират поотделно — ключовете са [a-z0-9/_.-] по
  // isSafeKey, но кодирането тук е евтина защита, ако правилото някога
  // се разхлаби.
  return "/" + key.split("/").map(encodeURIComponent).join("/");
}
